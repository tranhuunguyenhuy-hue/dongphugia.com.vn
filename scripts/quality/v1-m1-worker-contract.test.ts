import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
describe('M1 read-only source contract', () => {
  it('keeps snapshot rollback and requires separately provisioned Hyperdrive',()=>{
    const s=readFileSync('scripts/app-foundation/configure-v1-m1-worker-source.mjs','utf8')
    expect(s).toContain("['snapshot','postgresql']")
    expect(s).toContain("READONLY_HYPERDRIVE_ID_REQUIRED")
    expect(s).toContain("binding:'PUBLIC_DB'")
    const worker=readFileSync('apps/public/worker.ts','utf8')
    expect(worker).toContain("databaseMode")
    expect(worker).toContain("servePrerenderedCatalogue")
  })
  it('enforces parameterized read-only Postgres queries',()=>{
    const src=readFileSync('apps/public/src/runtime/public-db.ts','utf8')
    expect(src).toContain('PUBLIC_DATABASE_BINDING_REQUIRED')
    expect(src).toContain("statement.includes(';')")
    expect(src).toContain('client.query(statement, [...values])')
    expect(src).toContain('connectionTimeoutMillis: 3000')
    expect(src).toContain('query_timeout: 5000')
    expect(src).toContain('await client.end()')
  })
  it('proves the restricted Hyperdrive login before publishing and preserves a tested snapshot rollback',()=>{
    const workflow=readFileSync('.github/workflows/v1-worker-release.yml','utf8')
    const databaseProbe=readFileSync('scripts/app-foundation/public-db-preflight-worker.mjs','utf8')
    const publicSmoke=readFileSync('scripts/app-foundation/public-postgres-release-smoke.mjs','utf8')
    expect(workflow).toContain('x.hyperdrive[0].id!==process.env.V1_PUBLIC_HYPERDRIVE_ID')
    expect(workflow).toContain('workers_dev:false')
    expect(workflow).toContain('--remote --config "$RUNNER_TEMP/v1-release/wrangler.public-db-smoke.json"')
    expect(databaseProbe).toContain("current_user AS role")
    expect(databaseProbe).toContain('pg_stat_ssl')
    expect(databaseProbe).toContain('row_security_active')
    expect(databaseProbe).toContain('SELECT * FROM dpg_app.customers LIMIT 0')
    expect(databaseProbe).toContain('SELECT * FROM dpg_app.admin_users LIMIT 0')
    expect(databaseProbe).toContain("error?.code === '42501'")
    expect(publicSmoke).toContain("catalogueMode !== 'postgresql'")
    expect(publicSmoke).toContain('A-LFV-402S-1')
    expect(publicSmoke).toContain('BLOG_COUNT')
    expect(publicSmoke).toContain('checkImage(productImage)')
    expect(workflow).toContain('public-production-smoke.mjs')
    expect(workflow).toContain('node "$wrangler" rollback "$PREVIOUS_VERSION_ID"')
    expect(workflow).toContain("steps.deploy.outcome != 'skipped'")
  })
  it('collects sanitized preflight diagnostics without weakening the packaged PostgreSQL gate',()=>{
    const workflow=readFileSync('.github/workflows/v1-worker-release.yml','utf8')
    const diagnostics=readFileSync('scripts/app-foundation/v1-worker-preflight-diagnostics.mjs','utf8')
    expect(workflow).toContain("--noproxy '*' --connect-timeout 1 --max-time 2")
    expect(workflow).toContain("[ \"$last_status\" = '200' ] && [ \"$last_curl_exit\" -eq 0 ]")
    expect(workflow).toContain('public-postgres-release-smoke.mjs')
    expect(workflow).toContain('upload-artifact@v4')
    expect(workflow).toContain('path: ${{ runner.temp }}/v1-public-smoke-diagnostics/diagnostics.json')
    expect(workflow).toContain('retention-days: 1')
    expect(diagnostics).toContain("'worker_runtime_http_error'")
    expect(diagnostics).toContain("'public_application_http_error'")
    expect(diagnostics).toContain("'wrangler_remote_dev_session_error'")
    expect(diagnostics).toContain('MAX_LOG_CHARS')
    expect(diagnostics).toContain('REDACTED_DATABASE_URL')
  })
})
