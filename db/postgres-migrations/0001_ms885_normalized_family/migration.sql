-- MS885 normalized Product Family and configuration-group migration.
-- PostgreSQL origin only; never execute through prisma/migrations.
--
-- This migration deliberately does not read or write products.variant_group or
-- products.variant_group_id. Product/PDP identity and all Product-owned
-- commercial/publication fields remain unchanged.
--
-- MS885DW4#XW and MS885DW18#XW have approved manufacturer provenance but no
-- Product rows in the approved input. They are intentionally not fabricated;
-- the membership insert maps only Product rows that actually exist.

CREATE TABLE IF NOT EXISTS product_families (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_key varchar(100) NOT NULL,
  label varchar(200) NOT NULL,
  source varchar(50) NOT NULL DEFAULT 'manual',
  confidence varchar(20) NOT NULL DEFAULT 'medium',
  created_at timestamptz(6) NOT NULL DEFAULT now(),
  updated_at timestamptz(6) NOT NULL DEFAULT now(),
  CONSTRAINT product_families_family_key_key UNIQUE (family_key)
);

CREATE TABLE IF NOT EXISTS product_family_configuration_groups (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id integer NOT NULL,
  group_key varchar(100) NOT NULL,
  label varchar(200) NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  source varchar(50) NOT NULL DEFAULT 'manual',
  confidence varchar(20) NOT NULL DEFAULT 'medium',
  created_at timestamptz(6) NOT NULL DEFAULT now(),
  updated_at timestamptz(6) NOT NULL DEFAULT now(),
  CONSTRAINT uq_product_family_configuration_groups_family_key UNIQUE (family_id, group_key),
  CONSTRAINT uq_product_family_configuration_groups_id_family UNIQUE (id, family_id),
  CONSTRAINT product_family_configuration_groups_family_fkey
    FOREIGN KEY (family_id) REFERENCES product_families(id)
    ON DELETE CASCADE ON UPDATE NO ACTION
);

CREATE TABLE IF NOT EXISTS product_family_memberships (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id integer NOT NULL,
  configuration_group_id integer NOT NULL,
  product_id integer NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  source varchar(50) NOT NULL DEFAULT 'manual',
  confidence varchar(20) NOT NULL DEFAULT 'medium',
  created_at timestamptz(6) NOT NULL DEFAULT now(),
  updated_at timestamptz(6) NOT NULL DEFAULT now(),
  CONSTRAINT uq_product_family_memberships_family_product UNIQUE (family_id, product_id),
  CONSTRAINT product_family_memberships_family_fkey
    FOREIGN KEY (family_id) REFERENCES product_families(id)
    ON DELETE CASCADE ON UPDATE NO ACTION,
  CONSTRAINT product_family_memberships_configuration_group_fkey
    FOREIGN KEY (configuration_group_id, family_id)
    REFERENCES product_family_configuration_groups(id, family_id)
    ON DELETE CASCADE ON UPDATE NO ACTION,
  CONSTRAINT product_family_memberships_product_fkey
    FOREIGN KEY (product_id) REFERENCES products(id)
    ON DELETE CASCADE ON UPDATE NO ACTION
);

CREATE TABLE IF NOT EXISTS product_family_catalogue_gaps (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_id integer NOT NULL,
  member_key varchar(100) NOT NULL,
  gap_type varchar(50) NOT NULL DEFAULT 'missing_product',
  status varchar(30) NOT NULL DEFAULT 'open',
  source varchar(50) NOT NULL DEFAULT 'manual',
  confidence varchar(20) NOT NULL DEFAULT 'medium',
  note varchar(500),
  created_at timestamptz(6) NOT NULL DEFAULT now(),
  updated_at timestamptz(6) NOT NULL DEFAULT now(),
  CONSTRAINT uq_product_family_catalogue_gaps_family_member UNIQUE (family_id, member_key),
  CONSTRAINT product_family_catalogue_gaps_family_fkey
    FOREIGN KEY (family_id) REFERENCES product_families(id)
    ON DELETE CASCADE ON UPDATE NO ACTION
);

CREATE INDEX IF NOT EXISTS idx_product_families_source
  ON product_families (source);
CREATE INDEX IF NOT EXISTS idx_product_family_configuration_groups_order
  ON product_family_configuration_groups (family_id, sort_order);
CREATE INDEX IF NOT EXISTS idx_product_family_memberships_group_order
  ON product_family_memberships (configuration_group_id, sort_order, product_id);
CREATE INDEX IF NOT EXISTS idx_product_family_memberships_family_order
  ON product_family_memberships (family_id, sort_order, product_id);
CREATE INDEX IF NOT EXISTS idx_product_family_catalogue_gaps_status
  ON product_family_catalogue_gaps (family_id, status);

