import { readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const here = path.dirname(fileURLToPath(import.meta.url))
const workflow = readFileSync(path.join(here, '../../.github/workflows/environment-worker-publish.yml'), 'utf8')
const tokenIdentityChecker = readFileSync(path.join(here, 'verify-environment-worker-deployment-token.mjs'), 'utf8')
const releaseProtectionChecker = readFileSync(path.join(here, 'verify-environment-worker-release-protection.mjs'), 'utf8')
const productionBaselineChecker = readFileSync(path.join(here, 'verify-production-public-baseline.mjs'), 'utf8')
const deploymentVerifier = readFileSync(path.join(here, 'verify-environment-worker-deployment.mjs'), 'utf8')
const artifactDigestScript = readFileSync(path.join(here, 'environment-worker-artifact-digest.mjs'), 'utf8')
const ciWorkflow = readFileSync(path.join(here, '../../.github/workflows/environment-worker-ci.yml'), 'utf8')
const buildScript = readFileSync(path.join(here, 'build-environment-worker.mts'), 'utf8')
const namespaceScript = readFileSync(path.join(here, 'namespace-admin-vite-rsc-globals.mjs'), 'utf8')
const localRunner = readFileSync(path.join(here, 'run-local-preview.mjs'), 'utf8')
const browserVerifier = readFileSync(path.join(here, 'environment-worker-browser.mjs'), 'utf8')
const prBuildWorkflow = readFileSync(path.join(here, '../../.github/workflows/pr-preview-build.yml'), 'utf8')
const reviewSummaryScript = readFileSync(path.join(here, 'render-environment-worker-review-summary.mjs'), 'utf8')
const deployRunner = readFileSync(path.join(here, 'run-environment-worker-wrangler-deploy.mjs'), 'utf8')

function workflowJob(name) {
  const start = workflow.indexOf(`  ${name}:\n`)
  if (start < 0) throw new Error(`Missing workflow job ${name}`)
  const nextJob = workflow.slice(start + 1).search(/\n  [a-z][a-z0-9_-]*:\n/)
  return workflow.slice(start, nextJob < 0 ? undefined : start + 1 + nextJob)
}

describe('Staging Worker publication workflow trust boundaries', () => {
  it('serializes one Staging target and gates pre-merge source at the exact approved PR head', () => {
    expect(workflow).toContain('group: dpg-staging-publication')
    expect(workflow).toContain('options: [main, approved-pr]')
    expect(workflow).toContain('options: [staging]')
    expect(workflow).toContain('validate-environment-worker-source.mjs')
    expect(workflow).toContain('cloudflare-${{ inputs.environment }}')
    expect(workflow).not.toContain('dpg-preview')
    expect(workflow).not.toContain('https://dpg-preview.')
  })

  it('keeps credentials out of candidate builds and requires supervised external scope review', () => {
    const buildJob = workflowJob('build-candidate')
    const reviewJob = workflowJob('review-candidate')
    const publishJob = workflowJob('publish-candidate')
    const identityGate = publishJob.split('      - name: Verify actual token identity after required external policy review')[1]?.split('      - name: Deploy only the selected pre-created Worker')[0] || ''
    expect(buildJob).not.toMatch(/CLOUDFLARE_API_TOKEN|CLOUDFLARE_ACCOUNT_ID/)
    expect(buildJob).not.toContain('GITHUB_STEP_SUMMARY')
    expect(buildJob).not.toContain('Deployment token ID to inspect')
    expect(buildJob.match(/GITHUB_TOKEN: \$\{\{ github\.token \}\}/g)).toHaveLength(1)
    expect(buildJob.indexOf('GITHUB_TOKEN: ${{ github.token }}'))
      .toBeGreaterThan(buildJob.indexOf('Validate the source commit and approval'))
    expect(buildJob).toContain('dpg-environment-${{ inputs.environment }}-${{ inputs.source_sha }}')
    expect(reviewJob).toContain('needs: build-candidate')
    expect(reviewJob).toContain('Calculate artifact digest from downloaded candidate data')
    expect(reviewJob).toContain('environment-worker-artifact-digest.mjs')
    expect(reviewJob).toContain('dpg-environment-${{ inputs.environment }}-${{ inputs.source_sha }}')
    expect(reviewJob).toContain('RELEASE_DEPLOYMENT_TOKEN_ID: ${{ inputs.deployment_token_id }}')
    expect(reviewJob).toContain('RELEASE_SOURCE_SHA: ${{ inputs.source_sha }}')
    expect(reviewJob).toContain('RELEASE_API_ORIGIN_ACK: ${{ inputs.api_origin_ack }}')
    expect(reviewJob).toContain('RELEASE_ARTIFACT_SHA256: ${{ steps.artifact.outputs.sha256 }}')
    expect(reviewJob).toContain('render-environment-worker-review-summary.mjs')
    expect(reviewJob).not.toContain('working-directory: candidate')
    expect(reviewJob).not.toContain('npm ci')
    expect(reviewSummaryScript).toContain('Deployment token ID to inspect')
    expect(reviewSummaryScript).toContain('external human review')
    expect(reviewSummaryScript).toContain('Workers Editor role scoped to the existing dpg-staging Worker (Individual Workers scope)')
    expect(reviewSummaryScript).toContain('API-origin warning acknowledgement requested')
    expect(reviewSummaryScript).toContain('retains Wrangler --strict')
    expect(publishJob).toContain('needs: review-candidate')
    expect(publishJob).toContain('SOURCE_SHA: ${{ inputs.source_sha }}')
    expect(publishJob).toContain('ARTIFACT_SHA256: ${{ needs.review-candidate.outputs.artifact_sha256 }}')
    expect(publishJob).toContain('EXPECTED_DEPLOYMENT_TOKEN_ID: ${{ inputs.deployment_token_id }}')
    expect(publishJob).toContain('API_ORIGIN_ACK: ${{ inputs.api_origin_ack }}')
    expect(publishJob).toContain('dpg-environment-staging-${{ inputs.source_sha }}')
    expect(publishJob).not.toContain('needs.build-candidate.outputs')
    expect(publishJob).toContain('secrets.CLOUDFLARE_API_TOKEN')
    expect(publishJob).toContain('verify-environment-worker-deployment-token.mjs')
    expect(publishJob).toContain('prepare-environment-worker-publication.mjs')
    expect(publishJob).toContain('run-environment-worker-wrangler-deploy.mjs')
    expect(publishJob).not.toContain('wrangler.js deploy')
    expect(deployRunner).toContain("'--strict'")
    expect(deployRunner).toContain("delete childEnv.CI")
    expect(deployRunner).toContain("delete childEnv.GITHUB_ACTIONS")
    expect(deployRunner).toContain('ENVIRONMENT_WORKER_WRANGLER_UNEXPECTED_CONFIRMATION_DECLINED')
    expect(publishJob).toContain('environment:')
    expect(publishJob).toContain('name: cloudflare-${{ inputs.environment }}')
    expect(publishJob).toContain('Verify downloaded artifact identity before modifying it')
    expect(publishJob.indexOf('Verify downloaded artifact identity before modifying it'))
      .toBeLessThan(publishJob.indexOf('prepare-environment-worker-publication.mjs'))
    expect(publishJob.indexOf('Verify actual token identity after required external policy review'))
      .toBeLessThan(publishJob.indexOf('Deploy only the selected pre-created Worker'))
    expect(identityGate).toContain('secrets.CLOUDFLARE_API_TOKEN')
    expect(tokenIdentityChecker).toContain('/tokens/verify')
    expect(tokenIdentityChecker).toContain('policyScopeMachineVerified: false')
    expect(tokenIdentityChecker).toContain('external-required-reviewer-approval')
    expect(releaseProtectionChecker).toContain('/environments/${ENVIRONMENT}')
    expect(releaseProtectionChecker).toContain('/deployment-branch-policies')
    expect(releaseProtectionChecker).toContain('can_admins_bypass !== false')
    expect(releaseProtectionChecker).toContain('tranhuunguyenhuy-hue')
    expect(releaseProtectionChecker).not.toContain('CLOUDFLARE_API_TOKEN')
    expect(productionBaselineChecker).toContain("method: 'GET'")
    expect(productionBaselineChecker).not.toMatch(/method:\s*'(?:POST|PUT|PATCH|DELETE)'/)
    expect(deploymentVerifier).toContain("method: 'HEAD'")
    expect(publishJob.indexOf('Capture read-only Production public baseline before deployment'))
      .toBeLessThan(publishJob.indexOf('Deploy only the selected pre-created Worker'))
    expect(publishJob.indexOf('Compare read-only Production public baseline after Staging smoke'))
      .toBeGreaterThan(publishJob.indexOf('Verify active deployment identity, noindex and Production-published catalogue reads'))
    expect(artifactDigestScript).toContain('createHash(\'sha256\')')
    expect(publishJob).not.toContain('CLOUDFLARE_WORKER_POLICY_SCOPE')
    expect(publishJob).not.toContain('scripts/dongphugia-v1-public-production/settings')
  })

  it('allows only trusted-main manual dispatch and records nonsecret release identity evidence', () => {
    expect(workflow).toContain('  workflow_dispatch:')
    expect(workflow).not.toMatch(/^  (push|pull_request|schedule|workflow_run):/m)
    expect(workflow).toContain('github.ref == \'refs/heads/main\'')
    expect(workflow).toContain('deployment_token_id:')
    expect(workflow).toContain('api_origin_ack:')
    expect(workflow).toContain('options: [none, dpg-staging-script-api-origin-v1]')
    expect(workflow).toContain('actions: read')
    expect(workflow).toContain('verify-environment-worker-release-protection.mjs')
    expect(workflow).toContain('32-character lowercase Cloudflare token ID')
    expect(workflow).toContain('Token policy evidence: external human inspection')
    expect(workflow).toContain('Expected and API-verified token ID')
    expect(workflow).toContain('Candidate artifact content SHA-256')
    expect(workflow).toContain('Deployment config SHA-256')
    expect(workflow).toContain('Production public baseline comparison')
    expect(workflow).toContain('environment approval event')
  })

  it('publishes only the fixed Staging Worker and its matching workers.dev origin', () => {
    expect(workflow).not.toContain("'dpg-preview'")
    expect(workflow).toContain('APP_WORKER_NAME: dpg-staging')
    expect(workflow).toContain('https://dpg-staging.tranhuunguyenhuy.workers.dev')
    expect(workflow).toContain('d54f3402b9d112ab64d6135e0e3f1fb1')
    expect(workflow).toContain('fixed Production catalogue paths')
    expect(workflow).toContain('Admin auth is disabled and private data remains unavailable')
  })

  it('keeps Preview local-only and uses one origin for Public and Admin', () => {
    expect(ciWorkflow).toContain("worker_name='dpg-local-preview'")
    expect(ciWorkflow).toContain("origin='http://127.0.0.1:8787'")
    expect(ciWorkflow).not.toContain('dpg-preview')
    expect(ciWorkflow).not.toMatch(/CLOUDFLARE_(?:API_TOKEN|.*EDITOR_TOKEN)/)
    expect(buildScript).toContain("preview: { workerName: 'dpg-local-preview', origin: 'http://127.0.0.1:8787', localOnly: true }")
    expect(buildScript).toContain('workers_dev: !target.localOnly')
    expect(localRunner).toContain("const origin = 'http://127.0.0.1:8787'")
    expect(localRunner).toContain("'dev', '--local'")
    expect(prBuildWorkflow).toContain('name: PR App source build')
    expect(prBuildWorkflow).toContain('APP_ORIGIN: http://127.0.0.1:8787')
    expect(prBuildWorkflow).not.toContain('public-preview.invalid')
    expect(prBuildWorkflow).not.toContain('actions/upload-artifact')
    expect(prBuildWorkflow).not.toContain('PREVIEW_CLOUDFLARE_API_TOKEN')
  })

  it('keeps local Wrangler persistence outside the candidate before workflow upload', () => {
    expect(workflow.indexOf('environment-worker-browser.mjs'))
      .toBeLessThan(workflow.indexOf('actions/upload-artifact'))
    expect(browserVerifier).toContain("mkdtemp(path.join(os.tmpdir(), 'dpg-environment-worker-'))")
    expect(browserVerifier).toContain("'--persist-to', persistenceDirectory")
    expect(browserVerifier).toContain("rm(path.join(artifactRoot, '.wrangler'), { recursive: true, force: true })")
    expect(browserVerifier).toContain("rm(persistenceDirectory, { recursive: true, force: true })")
  })

  it('namespaces Admin RSC globals before combining both framework runtimes', () => {
    expect(buildScript).toContain('namespaceAdminViteRscGlobals')
    expect(buildScript).toContain("contract: 'dpg:combined-environment-worker:v2'")
    expect(namespaceScript).toContain('__vite_rsc_client_require__')
    expect(namespaceScript).toContain('__vite_rsc_require__')
    expect(namespaceScript).toContain('__vite_rsc_server_require__')
    expect(namespaceScript).toContain('__dpg_rsc0_')
    expect(namespaceScript).toContain('ADMIN_VITE_RSC_RUNTIME_GLOBAL_MISSING')
  })
})
