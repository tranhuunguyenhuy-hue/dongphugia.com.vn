-- Fail closed on the exact approved group, membership, and gap contract.
-- A zero-row Product table is valid in an isolated structural replay and
-- produces zero memberships plus two open catalogue gaps.
DO $$
DECLARE
  existing_count integer;
  mapped_count integer;
  mismatch_count integer;
  extra_membership_count integer;
  expected_gap_count integer;
  actual_gap_count integer;
  product_row_count integer;
  missing_required_count integer;
BEGIN
  IF (
    SELECT count(*)
    FROM product_family_configuration_groups configuration_group
    JOIN product_families family ON family.id = configuration_group.family_id
    WHERE family.family_key = 'toto:ms885'
  ) <> 3
  OR (
    SELECT count(*)
    FROM product_family_configuration_groups configuration_group
    JOIN product_families family ON family.id = configuration_group.family_id
    WHERE family.family_key = 'toto:ms885'
      AND configuration_group.group_key IN ('ecowasher', 'electronic-washlet', 'soft-close')
  ) <> 3 THEN
    RAISE EXCEPTION 'MS885 configuration-group contract mismatch';
  END IF;

  SELECT count(*) INTO existing_count
  FROM products product
  JOIN ms885_approved_members approved ON approved.member_key = product.sku;

  SELECT count(*) INTO product_row_count FROM products;

  SELECT count(*) INTO missing_required_count
  FROM ms885_approved_members approved
  LEFT JOIN products product ON product.sku = approved.member_key
  WHERE NOT approved.catalogue_gap
    AND product.id IS NULL;

  SELECT count(*) INTO mapped_count
  FROM product_family_memberships membership
  JOIN products product ON product.id = membership.product_id
  JOIN product_families family ON family.id = membership.family_id
  JOIN ms885_approved_members approved ON approved.member_key = product.sku
  WHERE family.family_key = 'toto:ms885';

  SELECT count(*) INTO mismatch_count
  FROM products product
  JOIN ms885_approved_members approved ON approved.member_key = product.sku
  JOIN product_families family ON family.family_key = 'toto:ms885'
  LEFT JOIN product_family_memberships membership
    ON membership.family_id = family.id
   AND membership.product_id = product.id
  LEFT JOIN product_family_configuration_groups configuration_group
    ON configuration_group.id = membership.configuration_group_id
   AND configuration_group.family_id = family.id
  WHERE membership.id IS NULL
     OR configuration_group.group_key IS DISTINCT FROM approved.group_key;

  SELECT count(*) INTO extra_membership_count
  FROM product_family_memberships membership
  JOIN products product ON product.id = membership.product_id
  JOIN product_families family ON family.id = membership.family_id
  LEFT JOIN ms885_approved_members approved ON approved.member_key = product.sku
  WHERE family.family_key = 'toto:ms885'
    AND approved.member_key IS NULL;

  SELECT count(*) INTO expected_gap_count
  FROM ms885_approved_members
  WHERE catalogue_gap;

  SELECT count(*) INTO actual_gap_count
  FROM product_family_catalogue_gaps gap
  JOIN product_families family ON family.id = gap.family_id
  WHERE family.family_key = 'toto:ms885';

  IF existing_count <> mapped_count
     OR (product_row_count <> 0 AND missing_required_count <> 0)
     OR mismatch_count <> 0
     OR extra_membership_count <> 0 THEN
    RAISE EXCEPTION
      'MS885 normalized membership contract mismatch: existing %, mapped %, missing required %, mismatches %, extras %',
      existing_count, mapped_count, missing_required_count, mismatch_count, extra_membership_count;
  END IF;

  IF product_row_count <> 0 AND EXISTS (
    WITH expected_groups (group_key, expected_without_gaps) AS (
      VALUES
        ('ecowasher', 3),
        ('electronic-washlet', 13),
        ('soft-close', 3)
    ),
    group_counts AS (
      SELECT expected.group_key,
             expected.expected_without_gaps
               + count(product.id) FILTER (WHERE approved.catalogue_gap) AS expected_count,
             count(product.id) AS actual_count
      FROM expected_groups expected
      LEFT JOIN ms885_approved_members approved
        ON approved.group_key = expected.group_key
      LEFT JOIN products product ON product.sku = approved.member_key
      GROUP BY expected.group_key, expected.expected_without_gaps
    )
    SELECT 1 FROM group_counts WHERE expected_count <> actual_count
  ) THEN
    RAISE EXCEPTION 'MS885 configuration-group membership cardinality mismatch';
  END IF;

  IF actual_gap_count <> expected_gap_count
     OR EXISTS (
       SELECT 1
       FROM ms885_approved_members approved
       LEFT JOIN product_families family ON family.family_key = 'toto:ms885'
       LEFT JOIN product_family_catalogue_gaps gap
         ON gap.family_id = family.id
        AND gap.member_key = approved.member_key
       WHERE approved.catalogue_gap AND gap.id IS NULL
     )
     OR EXISTS (
       SELECT 1
       FROM product_family_catalogue_gaps gap
       JOIN product_families family ON family.id = gap.family_id
       LEFT JOIN ms885_approved_members approved
         ON approved.member_key = gap.member_key
        AND approved.catalogue_gap
       WHERE family.family_key = 'toto:ms885'
         AND approved.member_key IS NULL
     ) THEN
    RAISE EXCEPTION 'MS885 catalogue-gap set is not exact';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM ms885_approved_members approved
    JOIN product_families family ON family.family_key = 'toto:ms885'
    JOIN product_family_catalogue_gaps gap
      ON gap.family_id = family.id
     AND gap.member_key = approved.member_key
    LEFT JOIN products product ON product.sku = approved.member_key
    WHERE approved.catalogue_gap
      AND gap.status IS DISTINCT FROM CASE
        WHEN product.id IS NULL THEN 'open' ELSE 'resolved' END
  ) THEN
    RAISE EXCEPTION 'MS885 catalogue-gap status mismatch';
  END IF;
END $$;
